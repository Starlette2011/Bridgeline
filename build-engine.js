'use strict';
/**
 * Bundles the shared engine (src/*) into public/js/engine.js so the app runs entirely in the
 * browser (GitHub Pages, any static host, or a double-clicked index.html). No dependencies.
 * Run: npm run build      (the output is committed; `npm test` fails if it is out of date)
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'src');
const OUT = path.join(__dirname, '..', 'public', 'js', 'engine.js');
const MODULES = ['languages', 'json', 'redact', 'schema', 'prompts', 'readability', 'heuristic', 'demo', 'clarity', 'engine'];

function bundle() {
  let out = '/* AUTO-GENERATED by scripts/build-engine.js from src/*. Do not edit; run `npm run build`. */\n(function () {\n  var defs = {};\n';
  for (const name of MODULES) {
    const code = fs.readFileSync(path.join(SRC, `${name}.js`), 'utf8').replace(/\r\n/g, '\n');
    out += `  defs[${JSON.stringify('./' + name)}] = function (module, exports, require) {\n${code}\n  };\n`;
  }
  out += `  var cache = {};
  function req(name) {
    if (!defs[name]) throw new Error('Bridgeline engine: missing module ' + name);
    if (!cache[name]) {
      var m = { exports: {} };
      cache[name] = m;
      defs[name](m, m.exports, req);
    }
    return cache[name].exports;
  }
  window.BLEngine = req('./engine');
})();
`;
  return out;
}

if (require.main === module) {
  fs.writeFileSync(OUT, bundle());
  console.log('Wrote', path.relative(process.cwd(), OUT));
}
module.exports = { bundle, OUT };
